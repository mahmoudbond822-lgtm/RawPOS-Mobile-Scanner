package com.rawpos.scanner.core.net

import java.util.UUID

/** Why a delivery did not end with a cart decision. */
enum class DeliveryError {
    /** The retry budget ran out without an acknowledgment. The cashier must check the desktop. */
    UNCERTAIN,

    /** An attempt never reached the desktop, and the budget is spent. Rescan. */
    EXPIRED,

    /** The token is missing, invalid, or revoked. Re-pair. */
    UNAUTHORIZED,

    /** The desktop refused this body; retrying it would be wrong. */
    REFUSED,
}

/** What the scanner tells the cashier. */
sealed interface Delivery {
    data class Decided(
        val status: String,
        val context: String?,
        val originalStatus: String? = null,
        val reasonCode: String? = null,
        val messageCode: String? = null,
    ) : Delivery

    data class Failed(val error: DeliveryError, val messageCode: String? = null) : Delivery
}

/**
 * One physical presentation, and the identity that must survive every retry.
 *
 * A retry that minted a new id would look like a second scan to the desktop, so the id lives here and
 * is never regenerated by the client.
 */
data class ScanEvent(
    val eventId: String = UUID.randomUUID().toString(),
    val barcode: String,
    val format: String,
    val sequence: Long,
    val scannedAtMillis: Long,
) {
    companion object {
        const val FORMAT_EAN_13 = "ean_13"
        const val FORMAT_EAN_8 = "ean_8"
        const val FORMAT_UPC_A = "upc_a"
        const val FORMAT_CODE_128 = "code_128"
        const val FORMAT_UNKNOWN = "unknown"

        fun forFormat(barcode: String, format: String, sequence: Long, nowMillis: Long): ScanEvent =
            ScanEvent(
                barcode = barcode,
                format = format,
                sequence = sequence,
                scannedAtMillis = nowMillis,
            )
    }
}
